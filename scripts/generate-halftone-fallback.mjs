/**
 * Pre-renders the portrait photo into a static grid of halftone dots, saved
 * as a TypeScript data module and used as the non-interactive fallback in
 * `components/ui/halftone-portrait.tsx` (no-JS, `prefers-reduced-motion`, or
 * no canvas support).
 *
 * The ink formula mirrors `lib/halftone/sample-image.ts` exactly so the
 * static fallback and the live canvas render the same portrait the same way.
 * Re-run this script (`node scripts/generate-halftone-fallback.mjs`) whenever
 * `public/profile-photo.png` changes. Requires `sharp` (already present as a
 * transitive dependency of `next`, or install with `npm i -D sharp`).
 */
import sharp from "sharp";
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.join(__dirname, "..", "public", "profile-photo.png");
const OUTPUT = path.join(__dirname, "..", "lib", "halftone", "portrait-fallback-dots.ts");

// Grid resolution — chosen to match the source photo's aspect ratio (400:514)
// closely, at a density comparable to the live canvas's finest (large
// viewport) grid. Vector output means one resolution serves every rendered
// size, from the ~40px home avatar to the ~400px About portrait.
const COLS = 56;
const ROWS = 72;

// Mirrors lib/halftone/sample-image.ts.
const BLACK_POINT = 0.08;
const WHITE_POINT = 0.86;
const CONTRAST_GAMMA = 1.4;
const ALPHA_CUTOFF = 16;

// Mirrors lib/halftone/grid.ts's MAX_RADIUS_TO_SPACING_RATIO, applied to an
// arbitrary SVG unit (the viewBox scales to any rendered size).
const SPACING_UNIT = 10;
const MAX_RADIUS = SPACING_UNIT * 0.46;
/** Skip dots too small to render meaningfully, to keep the data file lean. */
const INK_EPSILON = 0.02;

function clamp01(value) {
  return Math.min(1, Math.max(0, value));
}

async function main() {
  const { data, info } = await sharp(SOURCE)
    .resize(COLS, ROWS, { fit: "cover" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  if (info.width !== COLS || info.height !== ROWS) {
    throw new Error(`Unexpected resize output: ${info.width}x${info.height}`);
  }

  const dots = [];
  for (let row = 0; row < ROWS; row++) {
    for (let col = 0; col < COLS; col++) {
      const i = row * COLS + col;
      const offset = i * 4;
      const alpha = data[offset + 3];
      if (alpha < ALPHA_CUTOFF) continue;

      const luminance = (0.299 * data[offset] + 0.587 * data[offset + 1] + 0.114 * data[offset + 2]) / 255;
      const normalized = clamp01((WHITE_POINT - luminance) / (WHITE_POINT - BLACK_POINT));
      const ink = Math.pow(normalized, CONTRAST_GAMMA) * (alpha / 255);
      if (ink < INK_EPSILON) continue;

      const cx = SPACING_UNIT / 2 + col * SPACING_UNIT;
      const cy = SPACING_UNIT / 2 + row * SPACING_UNIT;
      const r = ink * MAX_RADIUS;
      dots.push([round(cx), round(cy), round(r)]);
    }
  }

  const viewBoxWidth = COLS * SPACING_UNIT;
  const viewBoxHeight = ROWS * SPACING_UNIT;

  const contents = `// Generated by scripts/generate-halftone-fallback.mjs — do not edit by hand.
// Re-run that script after replacing public/profile-photo.png.

/** A static halftone dot grid pre-rendered from the portrait photo, used as
 * the non-interactive fallback rendering (no JS, reduced motion, or no
 * canvas support) in \`components/ui/halftone-portrait.tsx\`. Each tuple is
 * \`[cx, cy, r]\` in the same arbitrary SVG unit as \`viewBoxWidth\`/\`viewBoxHeight\`. */
export const PORTRAIT_HALFTONE_FALLBACK = {
  viewBoxWidth: ${viewBoxWidth},
  viewBoxHeight: ${viewBoxHeight},
  dots: ${JSON.stringify(dots)},
} as const;
`;

  await writeFile(OUTPUT, contents, "utf8");
  console.log(`Wrote ${dots.length} dots to ${path.relative(process.cwd(), OUTPUT)}`);
}

function round(value) {
  return Math.round(value * 100) / 100;
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
